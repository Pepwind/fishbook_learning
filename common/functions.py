# coding: utf-8
import numpy as np

"""恒等函数：输出层 + 回归问题"""
def identity_function(x):
    return x

"""
    激活函数：
        对于神经网络学习来说,激活函数导数不在多数为0非常重要。若为0,则权重参数的改变不会影响损失函数，权重更新停止。损失函数值保持不变。
"""


"""
    阶跃函数：
        1.以阈值为界，超过阈值就切换为输出。“急剧变化”; 
        2.多用于感知机 ;
        3.属于激活函数。
        
    为何不能用于神经网络？
        阶跃函数作为激活函数，神经网络的学习将无法进行。，阶跃函数的导数在绝大多数地方（除了0以外的地方）均为0。
        也就是说，如果使用了阶跃函数，那么即便将损失函数作为指标，参数的微小变化也会被阶跃函数抹杀，导致损失函数的值不会产生任何变化。
"""
def step_function(x):
    return np.array(x > 0, dtype=np.int)



""" 
    sigmoid函数：
        1. 相对于阶跃函数，非常平滑，随着输入信号做连续变化; 
        2. 随着输入信号的增大而增大，输出值的范围为 0-1 之间,Sigmoid 输出压在 (0,1)天然可以当概率用。形状为S 型平滑曲线，两端压扁;
        3. 属于激活函数,多用于隐藏层;
        4. 由于含指数运算，故计算速度较慢；
        5. 梯度消失问题：
           它的导数 sigma'(x)=sigma(x)(1-sigma(x))，最大值只有 0.25（在 x=0 处）,当|x|稍大（比如 >5 或 <-5）时，
           梯度几乎衰减到 0。故只用于层数小于3层的神经网络;
        6. 稀疏度稠密：Sigmoid 所有神经元都在输出非零值，稠密激活。
"""
def sigmoid(x):
    return 1 / (1 + np.exp(-x))    


def sigmoid_grad(x):
    return (1.0 - sigmoid(x)) * sigmoid(x)
    

"""
    relu函数：
        1，输出范围为[0,正无穷), 图像为折线：负数归零，正数原样通过;
        2，计算速度一般较快;
        3. 正区间梯度恒为1：x>0 时导数恒为 1，连乘不会衰减，梯度能顺利传回浅层，极大缓解了梯度消失;
        4. 网络较稀疏：ReLU 把负输入直接置 0，意味着约一半神经元"沉默"了，网络更稀疏、更像生物神经元，也有一定的正则化效果;
        5，死亡神经元现象：
           如果某个神经元输入长期为负，梯度恒为 0，权重再也无法更新，这个神经元就"永久死亡"了。学习率设置过大时尤其容易触发。
           改进方法有：Leaky ReLU / PReLU / ELU。
        6. 深度学习隐藏层首选。 
"""
def relu(x):
    return np.maximum(0, x)


def relu_grad(x):
    grad = np.zeros(x)
    grad[x>=0] = 1
    return grad




"""
    softmax函数：
        1. softmax函数输出结果为0.0到1.0之间的实数，且函数输出总和为1。故将softmax函数输出解释为“概率”。
        2，由于y = exp(x)为递增函数，故不会改变元素之间的大小关系。
        
        注意：输出层softmax函数可省略
        1.神经网络只是把输出值最大神经元所对应类别作为识别结果，且softmax函数输出值最大神经元的位置也不会改变，故可省略。
        2.在实际的问题中,由于指数函数的运算需要一定的计算机运算量,因此输出层的softmax函数一般会被省略。
"""
def softmax(x):
    if x.ndim == 2:
        x = x.T
        x = x - np.max(x, axis=0)
        y = np.exp(x) / np.sum(np.exp(x), axis=0)
        return y.T 

    x = x - np.max(x) # 溢出对策
    return np.exp(x) / np.sum(np.exp(x))


"""
    损失函数：
       1. 神经网络以某个指标为线索寻找最优权重参数。神经网络的学习中所用的指标称为损失函数（loss function）;
       2. 一般用均方误差和交叉熵误差等;
       3. 是表示神经网络性能的“恶劣程度”的指标，即当前的神经网络对监督数据在多大程度上不拟合，在多大程度上不一致。故如
          果给损失函数乘上一个负值，就可以解释为“在多大程度上不坏”，即“性能有多好”。
       4. 机器学习使用训练数据进行学习。使用训练数据进行学习，严格来说，就是针对训练数据计算损失函数的值，找出使该值尽可
          能小的参数。因此，计算损失函数时必须将所有的训练数据作为对象。
          -->小批量（mini_batch），全部数据作为对象求损失函数和往往计算时间较长，特别大的话显然不现实。故神经网络的学习
          从训练数据中选出一批数据（作为全部的近似），然后对每个mini-batch进行学习。
       5. 对于N份数据来说，将N份数据求损失函数和后再除以N进行正规化。得到可求单个数据的"平均损失函数"。
           平均化好处是可获得和训练数据的数量无关的统一指标。

    为何要设定损失函数？
        在神经网络的学习中，寻找最优参数（权重和偏置）时要寻找使得损失函数值尽量小的参数。而为了找这个使得损失函数值尽可能小
        的范围，需要计算参数的导数（即梯度），来确定更新参数的值的方向。
        -->比如：假设有一个神经网络，现在我们来关注这个神经网络中的某一个权重参数。
           对该权重参数的损失函数求导（如果稍微改变这个权重参数的值，损失函数的值会如何变化）：
             1.若导数值为负，则增加权重参数值可减少损失函数值。
             2.若导数值为正，则权重参数与损失函数成正比。
             3.导数为0则权重参数的改变不会影响损失函数，权重更新停止。损失函数值保持不变。

    为何不用识别精度作为指标？
        因为这样一来参数的导数绝大多数地方变为0，参数无法更新。识别精度对微小的参数变化基本上没有什么反应，即便有反应，它的值
        也是不连续地、突然地变化。
"""



"""
    均方误差：
        1. y表示神经网络的输出，t表示监督数据;
        2. 值越小，损失越小，性能越好。
"""
def mean_squared_error(y, t):
    return 0.5 * np.sum((y-t)**2)



"""
    交叉熵误差：
        1. y是神经网络的输出,t是监督数据。并且，t也可以为正确解标签：t中只有被正确解标签的索引为1，其他均为0（one-hot表示）;
        2. 交叉熵误差的值是由正确解标签所对应的输出结果决定的;
        3. 函数中加1e-7是为了防止负无群大(-inf)发生;
        4. 值越小，损失越小，性能越好。
"""
"""监督数据为标签形式（非one-hot表示版本像“2”“7”这样的标签）"""
def cross_entropy_error(y, t):
    # y的维度为1时，即求单个数据的交叉熵误差时，要改变数据的形状。
    if y.ndim == 1:
        t = t.reshape(1, t.size)
        y = y.reshape(1, y.size)
        
    # 监督数据是one-hot-vector的情况下，转换为正确解标签的索引
    if t.size == y.size:
        t = t.argmax(axis=1)
             
    batch_size = y.shape[0] #批量大小
    # 当输入为mini-batch时，要用batch的个数进行正规化，计算单个数据的平均交叉熵误差。
    return -np.sum(np.log(y[np.arange(batch_size), t] + 1e-7)) / batch_size

"""监督数据为正确解标签（one-hot版）"""
def cross_entropy_error2(y, t):
    # y的维度为1时，即求单个数据的交叉熵误差时，要改变数据的形状。
    if y.ndim == 1:
        t = t.reshape(1, t.size)
        y = y.reshape(1, y.size)

    batch_size = y.shape[0]  # 批量大小
    # 当输入为mini-batch时，要用batch的个数进行正规化，计算单个数据的平均交叉熵误差。
    return -np.sum(t * np.log(y + 1e-7)) / batch_size


def softmax_loss(X, t):
    y = softmax(X)
    return cross_entropy_error(y, t)
